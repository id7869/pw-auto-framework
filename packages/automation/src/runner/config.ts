/**
 * 为每次 run 生成官方 playwright.config.ts（确定性，无用户输入拼接到代码结构里）。
 *
 * 官方依据：
 * - config 选项：https://playwright.dev/docs/test-configuration（testDir/outputDir/timeout/retries/workers/fullyParallel/
 *   failOnFlakyTests/reporter/use/projects）
 * - trace/screenshot/video：https://playwright.dev/docs/test-use-options
 * - 代理：https://playwright.dev/docs/network#http-proxy（use.proxy{server,bypass}）
 */

import path from 'node:path';

import type { ResolvedEngineRunOptions } from '../types.ts';
import { jsonLiteral } from '../compiler/expressions.ts';

export const PLAYWRIGHT_PROJECT_NAME = 'pw-auto';

export interface PlaywrightConfigInput {
  workspaceDir: string;
  specsDir: string;
  outputDir: string;
  reportPath: string;
  htmlReportDir?: string;
  options: ResolvedEngineRunOptions;
}

export interface GeneratedPlaywrightConfig {
  configPath: string;
  content: string;
}

interface BrowserSelection {
  browserName: 'chromium' | 'firefox' | 'webkit';
  channel?: 'chrome' | 'msedge';
}

export function mapBrowserSelection(browser: ResolvedEngineRunOptions['browser']): BrowserSelection {
  switch (browser) {
    case 'chrome':
      return { browserName: 'chromium', channel: 'chrome' };
    case 'msedge':
      return { browserName: 'chromium', channel: 'msedge' };
    case 'firefox':
      return { browserName: 'firefox' };
    case 'webkit':
      return { browserName: 'webkit' };
    case 'chromium':
    default:
      return { browserName: 'chromium' };
  }
}

function assertAbsolute(label: string, value: string): void {
  if (!path.isAbsolute(value)) {
    throw new Error(`${label} 必须是绝对路径：${value}`);
  }
}

/**
 * 生成配置文本与路径。纯函数（不写盘），便于单测断言。
 */
export function buildPlaywrightConfig(input: PlaywrightConfigInput): GeneratedPlaywrightConfig {
  assertAbsolute('workspaceDir', input.workspaceDir);
  assertAbsolute('specsDir', input.specsDir);
  assertAbsolute('outputDir', input.outputDir);
  assertAbsolute('reportPath', input.reportPath);
  const browser = mapBrowserSelection(input.options.browser);

  const commonUse: string[] = [];
  commonUse.push(`headless: ${input.options.headed ? 'false' : 'true'}`);
  commonUse.push(`trace: ${jsonLiteral(input.options.trace)}`);
  commonUse.push(`screenshot: ${jsonLiteral(input.options.screenshot)}`);
  commonUse.push(`video: ${jsonLiteral(input.options.video)}`);
  if (input.options.proxy !== undefined) {
    const proxyParts = [`server: ${jsonLiteral(input.options.proxy.server)}`];
    if (input.options.proxy.bypass !== undefined) proxyParts.push(`bypass: ${jsonLiteral(input.options.proxy.bypass)}`);
    commonUse.push(`proxy: { ${proxyParts.join(', ')} }`);
  }

  const projectUse: string[] = [`browserName: ${jsonLiteral(browser.browserName)}`];
  if (browser.channel !== undefined) projectUse.push(`channel: ${jsonLiteral(browser.channel)}`);

  const reporterParts: string[] = [`['json', { outputFile: ${jsonLiteral(input.reportPath)} }]`];
  if (input.htmlReportDir !== undefined) {
    assertAbsolute('htmlReportDir', input.htmlReportDir);
    reporterParts.push(`['html', { outputFolder: ${jsonLiteral(input.htmlReportDir)}, open: 'never' }]`);
  }

  const lines: string[] = [];
  lines.push('// generated by pw-auto-framework; do not edit.');
  lines.push("import { defineConfig } from '@playwright/test';");
  lines.push('');
  lines.push('export default defineConfig({');
  lines.push(`  testDir: ${jsonLiteral(input.specsDir)},`);
  lines.push(`  outputDir: ${jsonLiteral(input.outputDir)},`);
  lines.push(`  timeout: ${input.options.caseTimeoutMs},`);
  lines.push(`  expect: { timeout: ${Math.min(5000, input.options.caseTimeoutMs)} },`);
  lines.push(`  retries: ${input.options.retries},`);
  lines.push(`  workers: ${input.options.workers},`);
  lines.push(`  fullyParallel: ${input.options.workers > 1 ? 'true' : 'false'},`);
  lines.push(`  failOnFlakyTests: ${input.options.failOnFlaky ? 'true' : 'false'},`);
  lines.push(`  reporter: [${reporterParts.join(', ')}],`);
  lines.push(`  use: { ${commonUse.join(', ')} },`);
  lines.push('  projects: [');
  lines.push(`    { name: ${jsonLiteral(PLAYWRIGHT_PROJECT_NAME)}, use: { ${projectUse.join(', ')} } },`);
  lines.push('  ],');
  lines.push('});');
  lines.push('');

  return {
    configPath: path.join(input.workspaceDir, 'playwright.config.ts'),
    content: lines.join('\n'),
  };
}